"""
Phase 5 of AMIE3 Pipeline: Biological Validation
================================================
Takes the novel predictions generated by AMIE and queries the PubMed database
to see if these "hidden" links have been discussed in recent scientific literature.

This proves that the AMIE rules are accurately predicting real biology!

Usage:
    uv run python scripts/validate_predictions.py
"""

import csv
import urllib.request
import urllib.parse
import json
import time

PREDICTIONS_FILE = "outputs/novel_predictions.csv"
VALIDATION_OUTPUT = "outputs/validated_predictions.csv"

def search_pubmed(disease, target):
    """
    Queries PubMed for papers mentioning both the disease and the target gene/protein.
    Returns the number of matching papers.
    """
    # Let PubMed use its 'Automatic Term Mapping' by dropping strict quotes.
    # We also generalize the disease to just "Alzheimer" since the DB names are too specific.
    query = f"Alzheimer AND {target}"
    url = f"https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esearch.fcgi?db=pubmed&term={urllib.parse.quote(query)}&retmode=json"
    
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
        with urllib.request.urlopen(req) as response:
            data = json.loads(response.read().decode())
            return int(data["esearchresult"]["count"])
    except Exception as e:
        print(f"Error querying PubMed: {e}")
        return 0

def validate_predictions():
    print("\n[Validation] Reading novel predictions...")
    
    try:
        with open(PREDICTIONS_FILE, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            predictions = list(reader)
    except FileNotFoundError:
        print(f"[ERROR] Could not find {PREDICTIONS_FILE}. Run predict_links.py first.")
        return

    # Deduplicate targets (we might have predicted the same target via multiple rules)
    unique_targets = set()
    for p in predictions:
        unique_targets.add((p["Disease"], p["Predicted_Target"]))
    
    print(f"[Validation] Found {len(unique_targets)} unique disease-target pairs to validate.")
    print(f"[Validation] Querying PubMed for literature evidence (this takes a moment to respect API limits)...\n")

    results = []
    
    # We will test the first 15 unique targets to not spam the API
    test_limit = 200
    tested = 0
    
    for disease, target in unique_targets:
        if tested >= test_limit:
            break
            
        print(f"  Searching PubMed for: '{disease}' + '{target}' ... ", end="", flush=True)
        count = search_pubmed(disease, target)
        print(f"Found {count} papers!")
        
        results.append({
            "Disease": disease,
            "Target": target,
            "PubMed_Hit_Count": count
        })
        
        tested += 1
        time.sleep(0.5) # Be nice to PubMed API
        
    print(f"\n[SUCCESS] Validation complete for {tested} targets!")
    
    # Sort by hits descending
    results.sort(key=lambda x: x["PubMed_Hit_Count"], reverse=True)
    
    print("\n--- Top Validated Discoveries ---")
    successes = 0
    for res in results:
        if res["PubMed_Hit_Count"] > 0:
            print(f"[VALIDATED] {res['Target']} ({res['PubMed_Hit_Count']} published papers)")
            successes += 1
            
    if successes == 0:
        print("None of the tested predictions had exact matches in PubMed abstracts. These might be genuinely brand-new hypotheses!")
    else:
        print(f"\nSuccess! AMIE independently predicted {successes} biological associations that exist in literature but were missing from your Neo4j graph!")

    # Save the validation results
    print(f"\nSaving validation results to {VALIDATION_OUTPUT}...")
    with open(VALIDATION_OUTPUT, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["Disease", "Target", "PubMed_Hit_Count"])
        for res in results:
            writer.writerow([res["Disease"], res["Target"], res["PubMed_Hit_Count"]])

if __name__ == "__main__":
    validate_predictions()
